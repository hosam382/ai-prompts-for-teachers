// يتجاهل التشكيل والتطويل، ويوحّد أ إ آ ٱ إلى ا، وة إلى ه، وى إلى ي، والأرقام العربية إلى 0-9
export function normalize(str) {
  return String(str ?? '')
    .replace(/[ؐ-ًؚ-ٰٟۖ-ۜ۟-۪ۨ-ۭ]/g, '')
    .replace(/ـ/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

const categoryLabel = (id) => (CATEGORIES.find((c) => c.id === id) || {}).label || '';

// يرجع الأوامر اللي فيها كل كلمات البحث (في العنوان أو الوصف أو القسم أو نص الأمر)
// category: 'all' أو فاضي = كل الأقسام. اللي تطابق عناوينها تطلع أول، والباقي بنفس الترتيب
export function search(prompts, query = '', category = 'all') {
  const list = (prompts || []).filter((p) => !category || category === 'all' || p.category === category);
  const words = normalize(query).split(' ').filter(Boolean);
  if (!words.length) return list;
  const scored = [];
  list.forEach((p, i) => {
    const title = normalize(p.title);
    const hay = [title, normalize(p.when), normalize(categoryLabel(p.category)), normalize(p.template)].join(' \n ');
    if (!words.every((w) => hay.includes(w))) return;
    const score = words.filter((w) => title.includes(w)).length;
    scored.push({ p, i, score });
  });
  scored.sort((a, b) => b.score - a.score || a.i - b.i);
  return scored.map((s) => s.p);
}
