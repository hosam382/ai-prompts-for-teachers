// ───────── الفراغات ─────────
// [اسم] بدون أقواس متداخلة أو أسطر جديدة، وطوله معقول
const PH = /\[([^\[\]\n]{1,80})\]/g;

// أسماء الفراغات بترتيب أول ظهور، بدون تكرار
export function placeholders(template) {
  const seen = new Set();
  const out = [];
  for (const m of String(template ?? '').matchAll(PH)) {
    const name = m[1].trim();
    if (name && !seen.has(name)) { seen.add(name); out.push(name); }
  }
  return out;
}

function valueFor(values, name) {
  const v = values && Object.prototype.hasOwnProperty.call(values, name) ? values[name] : undefined;
  if (v === undefined || v === null) return null;
  const s = String(v).trim();
  return s === '' ? null : s;
}

// يعبّي الفراغات اللي لها قيمة، واللي ما لها قيمة (أو قيمتها فاضية) تبقى زي ما هي بين قوسين
export function fill(template, values = {}) {
  return String(template ?? '').replace(PH, (whole, inner) => {
    const v = valueFor(values, inner.trim());
    return v === null ? whole : v;
  });
}

// نفس fill لكن يرجع قطع عشان المعاينة تلوّن المعبّى والفاضي
// [{ type: 'text', text }, { type: 'filled', name, text }, { type: 'empty', name, text: '[name]' }]
export function segments(template, values = {}) {
  const src = String(template ?? '');
  const out = [];
  let last = 0;
  for (const m of src.matchAll(PH)) {
    const name = m[1].trim();
    if (!name) continue;
    if (m.index > last) out.push({ type: 'text', text: src.slice(last, m.index) });
    const v = valueFor(values, name);
    out.push(v === null ? { type: 'empty', name, text: m[0] } : { type: 'filled', name, text: v });
    last = m.index + m[0].length;
  }
  if (last < src.length) out.push({ type: 'text', text: src.slice(last) });
  return out;
}

